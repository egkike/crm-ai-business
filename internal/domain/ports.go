package domain

import "context"

// This file declares the driven ports of the configurable business
// configuration (RF6 workflows, RF7 areas): the interfaces the application layer
// depends on and the persistence adapter implements.
//
// The ports live in the domain because that is the direction of the dependency
// rule (AGENTS.md layer map: the domain owns the ports, the outer adapters
// implement them). The carriers they exchange are domain entities — a
// WorkflowConfig, an Area — and never wire shapes: no JSON tags, no SQL, no
// transport input structs. F1's ticket ports still live in
// internal/application/usecase, where the F1 use cases that own them were born;
// new configuration ports start here so the next phase does not add a fifth
// dialect of the same interface.

// WorkflowConfigStore is the driven port of the workflow configuration: the
// three config tables (ticket_types, ticket_states, ticket_transitions) read and
// written as the single aggregate the Owner edits (PRD §3.7, RF6).
//
// The aggregate boundary is the point of the port. A workflow is configured as a
// whole and rejected as a whole ("se rechaza la config completa y nada queda
// parcialmente escrito"), so there is no method that adds "just one state" or
// "just one transition": every write replaces the config of a type inside one
// transaction, and a failure leaves the previous config intact.
type WorkflowConfigStore interface {
	// LoadConfig assembles the workflow of the ticket type named typeName: the
	// type row (its default area) plus its states and transitions in declaration
	// order. found=false means no type carries that name.
	//
	// The returned config is NOT validated: it is what the database holds, which
	// is only guaranteed valid if every writer went through Validate first. The
	// readers that act on a config (the engine, the admin tools) validate it
	// again when the answer depends on it being executable.
	LoadConfig(ctx context.Context, typeName string) (WorkflowConfig, bool, error)

	// SaveConfig replaces the whole workflow of an EXISTING ticket type: the
	// type's default area, all of its states and all of its transitions, in one
	// transaction. found=false means no type carries cfg.TypeName, in which case
	// nothing is written — creating a type is a separate decision (RF6's admin
	// tools own it), never a side effect of saving a config.
	//
	// The adapter persists what it is given (its job is the transaction
	// boundary); the semantic validation of the config is the use case's, which
	// calls WorkflowConfig.Validate before it gets here.
	SaveConfig(ctx context.Context, cfg WorkflowConfig) (bool, error)
}

// Area is one configurable service area (PRD §3.7, RF7): a name and the internal
// accounts that are its members. It is a domain entity, so it carries no wire
// tags; the transport adapters map it.
//
// The 'Ventas' area that the seeding migration creates is an ordinary row: it
// can be renamed like any other, and the 'venta' ticket type points at it by id.
type Area struct {
	// ID is the internal UUID primary key.
	ID string

	// Name is the human-facing area name, unique among areas.
	Name string

	// CreatedAt and UpdatedAt are the stored ISO-8601 UTC timestamps.
	CreatedAt string
	UpdatedAt string
}

// AreaStore is the driven port of the configurable areas (RF7: "el Owner
// crea/renombra/elimina áreas y les asigna staff").
//
// The port exposes what the F2 use cases need and nothing else: there is no
// delete yet — deleting an area is a destructive operation with a double gate
// (RF6's confirmation rule), and it lands with the admin tools that own that
// gate (T4) instead of being smuggled in as an unused method.
type AreaStore interface {
	// CreateArea inserts one area. The ID is generated by the application layer
	// (the same convention the ticket creation follows), so the adapter never
	// invents identity.
	CreateArea(ctx context.Context, area Area) error

	// RenameArea renames the area id and refreshes its updated_at. found=false
	// means no area carries that id, in which case nothing was written.
	RenameArea(ctx context.Context, id, name string) (bool, error)

	// ListAreas returns every area, ordered by name (case-insensitive).
	ListAreas(ctx context.Context) ([]Area, error)

	// AssignStaff makes accountID a member of areaID. Membership is a set: an
	// assignment that already exists is a no-op, not a failure (RF7's form can
	// be submitted twice).
	AssignStaff(ctx context.Context, areaID, accountID string) error

	// ListAreasByAccount returns the areas accountID is a member of, ordered by
	// name (case-insensitive). It is the read behind RF8's staff visibility rule
	// ("los no asignados de sus áreas").
	ListAreasByAccount(ctx context.Context, accountID string) ([]Area, error)
}
