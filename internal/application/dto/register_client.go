// Package dto holds the carriers that cross the application boundary: the
// shapes a use case receives, returns, and the shapes the persistence adapters
// implement against (AGENTS.md layer map, boundary contract 4). Carriers are
// wire-free and behavior-free; every decision lives in internal/application/
// usecase, every SQL statement in internal/repository.
//
// Why the persistence port types live here and not in internal/domain: the
// domain package does not exist yet (T4 landed without it, exactly like
// auth.CallerError). These carriers are the cross-layer contract of the
// registration seam, and they are documented so that when internal/domain lands
// they move there without changing a single call site. Until then, both
// internal/application/usecase (the port consumer) and internal/repository (the
// adapter) reference them, which is why they cannot live in either one.
package dto

import "fmt"

// Channel identifies the delivery channel a caller-id arrived on, and with it
// which natural identifier of a clients row carries it (PRD RF3): the WhatsApp
// channel delivers a phone, the e-mail channel delivers an address.
//
// The value doubles as the column name of the identifier, so a Channel can be
// compared with what a schema constraint rejected without a translation table.
type Channel string

const (
	// ChannelPhone is the WhatsApp-style channel: the identifier is a phone
	// stored verbatim (no trimming, no digit-only normalization).
	ChannelPhone Channel = "phone"
	// ChannelEmail is the e-mail channel: the identifier is an address stored
	// as received and matched case-insensitively through lower(email).
	ChannelEmail Channel = "email"
)

// Valid reports whether the channel is one the product knows. An unknown
// channel is a programming error, and callers of Valid treat it as fail-closed.
func (c Channel) Valid() bool {
	return c == ChannelPhone || c == ChannelEmail
}

// RegisterClientCommand is the input carrier of the anonymous registration
// seam.
//
// It carries a caller-id and an optional display name, and NOTHING ELSE. There
// is deliberately no role field: the channel transports an identity, never a
// role (PRD §3.8), and a parameter that could carry a role would be an
// injection seam.
type RegisterClientCommand struct {
	// CallerID is the X-Caller-Id header exactly as received. It is the only
	// identity signal of this use case and it is never normalized: a phone is
	// stored byte-exact and an e-mail is only case-folded by the schema index.
	CallerID string

	// DisplayName is the name the sender offered, if any. Empty means "use the
	// product default" (a masked derivation of the identifier).
	DisplayName string
}

// RegisterClientResult is the outcome of the anonymous registration seam.
//
// Created distinguishes a first admission from an idempotent one: the gateway
// retries register_client exactly once after an unknown caller, and the retry
// must succeed without creating a second client (RF3 acceptance criterion).
type RegisterClientResult struct {
	// ClientID is the internal UUID primary key of the clients row — the only
	// identity the business logic may use from here on.
	ClientID string

	// DisplayName is the name stored on the row (the requested one, the
	// masked default, or whatever an existing row already carries).
	DisplayName string

	// Created is true only when this call inserted the row.
	Created bool
}

// NewClient carries the clients row a registration attempt wants to insert.
//
// A client stores exactly one natural identifier at registration time: the
// channel that admitted it. The other one stays NULL and is claimed later, if
// ever (PRD RF3: WhatsApp-first creates with phone, e-mail-first creates with
// email and phone NULL).
type NewClient struct {
	// ID is the internal UUID primary key. It is generated by the application
	// layer (crypto/rand), never by the database.
	ID string

	// Channel selects which natural identifier column this row fills.
	Channel Channel

	// Identifier is the natural identifier, verbatim for a phone.
	Identifier string

	// DisplayName is the name stored on the row.
	DisplayName string
}

// ClientRecord carries the columns of an existing clients row that the
// application layer needs in order to answer a registration attempt
// idempotently.
type ClientRecord struct {
	// ID is the internal UUID primary key of the row.
	ID string

	// DisplayName is the name stored on the row. It may be empty: the column
	// has a DEFAULT '' and older rows are not backfilled.
	DisplayName string
}

// IdentifierTakenError is the persistence-level signal that the natural
// identifier of a registration attempt already belongs to another row.
//
// An adapter wraps the driver's UNIQUE violation in it — carrying the channel
// and the schema constraint that rejected the write, never the driver text —
// and the application layer renders the Spanish semantic rejection. This is the
// whole reason the type exists: a constraint name is a diagnostic, not
// something a client may ever read, and the application must be able to tell
// "this identifier is taken" apart from "the database is broken" without
// parsing an error string.
type IdentifierTakenError struct {
	// Channel is the identifier column that collided.
	Channel Channel

	// Constraint names the schema constraint that rejected the write. It is
	// diagnostics only: it must never cross the sanitization boundary.
	Constraint string
}

// Error implements error. The text is internal diagnostics (the Spanish
// rejection is rendered by the use case), so it is allowed to name the
// constraint.
func (e *IdentifierTakenError) Error() string {
	return fmt.Sprintf("identificador ya tomado: canal %q, restricción %q", string(e.Channel), e.Constraint)
}
