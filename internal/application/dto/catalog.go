package dto

// This file is the cross-layer contract of the RF4 catalog: the shapes a
// catalog use case receives and returns, and the shapes internal/repository
// implements against (AGENTS.md boundary contract 4). Carriers only — every
// decision lives in internal/application/usecase and every SQL statement in
// internal/repository.
//
// Money is INTEGER minor units (price_cents) everywhere in these carriers: a
// float would round, and the catalog is a purchase surface (PRD §3.7).

// CatalogKind is the RF4 vocabulary of a catalog item: a product to sell or a
// service to book.
type CatalogKind string

const (
	// CatalogKindProducto is a sellable item. It is never bookable, so it can
	// never carry a duration (PRD §3.7, the CHECK of catalog_items).
	CatalogKindProducto CatalogKind = "producto"

	// CatalogKindServicio is a bookable service: the only kind that may carry
	// duration_min.
	CatalogKindServicio CatalogKind = "servicio"
)

// Valid reports whether the kind is one the product knows. An unknown value is
// a rejected input, never a default.
func (k CatalogKind) Valid() bool {
	return k == CatalogKindProducto || k == CatalogKindServicio
}

// Bookable reports whether an item of this kind can be reserved (RF4: "solo
// servicios (con duration_min) son reservables"). An invalid kind answers
// false: never grant booking to an unknown value.
func (k CatalogKind) Bookable() bool {
	return k == CatalogKindServicio
}

// CatalogItemRecord is one stored catalog item as every consumer reads it: the
// search results and the create/update outcomes share this shape so Hermes can
// use one mental model for all three tools.
//
// UseCases and Limitations are the v1.11 agent knowledge: an empty string means
// the item says nothing about them (the columns are NULL), never "there are
// none".
type CatalogItemRecord struct {
	// ID is the internal UUID primary key.
	ID string

	// Kind is the RF4 vocabulary value stored on the row.
	Kind CatalogKind

	// Name is the item's name.
	Name string

	// Description is the short "what it is" of the item.
	Description string

	// UseCases is what problems the item solves and for whom (v1.11).
	UseCases string

	// Limitations is what the item explicitly does NOT cover (v1.11).
	Limitations string

	// PriceCents is the price in minor units, or nil when the price is not
	// published ("a consultar"). Never a float.
	PriceCents *int64

	// SalesURL is the optional online purchase deep-link.
	SalesURL string

	// DurationMin is the duration in minutes. Only a bookable service may carry
	// one; nil means "not stated".
	DurationMin *int
}

// CatalogItemInput is the editable payload of an item, shared by creation and
// update so the validation rules cannot drift between them.
//
// It is a full replacement, not a patch: the update use case writes every field
// it carries, which keeps "absent" and "explicitly empty" from meaning two
// different things (a nullable text column has no third state a caller could
// express through a JSON tool argument).
type CatalogItemInput struct {
	// Kind is the RF4 vocabulary value; unknown values are rejected.
	Kind CatalogKind

	// Name is the item's name; required.
	Name string

	// Description is the short "what it is"; optional, empty is allowed.
	Description string

	// UseCases is what problems the item solves (v1.11); optional.
	UseCases string

	// Limitations is what the item does not cover (v1.11); optional.
	Limitations string

	// PriceCents is the price in minor units; nil means "a consultar".
	PriceCents *int64

	// SalesURL is the optional online purchase deep-link.
	SalesURL string

	// DurationMin is the duration in minutes; nil means "not stated", and it is
	// rejected for a product.
	DurationMin *int
}

// NewCatalogItem carries the row a creation wants to insert.
type NewCatalogItem struct {
	// ID is the internal UUID primary key, generated by the application layer.
	ID string

	// Item is the validated payload.
	Item CatalogItemInput
}

// CatalogItemUpdate carries the replacement of an existing row.
type CatalogItemUpdate struct {
	// ID is the internal UUID primary key of the row to replace.
	ID string

	// Item is the validated payload that replaces the stored one.
	Item CatalogItemInput
}

// SearchCatalogQuery carries the full-text search of RF4: the free text the
// client's problem was phrased with, plus pagination.
type SearchCatalogQuery struct {
	// Text is the caller's own words. Empty means "browse the catalog": no
	// filter, active items by name. The repository turns it into a safe FTS5
	// expression — the text is never concatenated into SQL.
	Text string

	// Limit is the page size the application layer already normalized.
	Limit int

	// Offset is the number of results to skip.
	Offset int
}

// CatalogSearchResult is the answer of the search: the page that was actually
// served plus the pagination the application layer applied.
//
// The applied window travels back because the caller asked for a page, not for a
// page size: the transport echoes what the use case decided (a default limit, a
// capped one), never what the request happened to contain.
type CatalogSearchResult struct {
	// Items are the matching active items, best match first.
	Items []CatalogItemRecord

	// Limit is the page size applied.
	Limit int

	// Offset is the number of results skipped.
	Offset int
}
